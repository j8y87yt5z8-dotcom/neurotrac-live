    func testEveryKeyHasEnglish() {
        for k in Self.keys {
            XCTAssertNotNil(Translations.en[k], "missing English: \(k)")
        }
    }

    func testPlaceholdersPreserved() {
        for k in Self.keys {
            guard let e = Translations.en[k] else { continue }
            for p in ["{}", "%d", "%.0f", "%.1f", "%@", "%+.2f", "%02d", "%8.2f"] {
                XCTAssertEqual(k.components(separatedBy: p).count, e.components(separatedBy: p).count, "placeholder %\(p) in: \(k)")
            }
        }
    }

    func testInterpolation() {
        let m = 5
        XCTAssertEqual(tr("\(m) mois"), "5 months")
        XCTAssertEqual(trd("Droite"), "Right")
        XCTAssertEqual(trd("Muscle inconnu"), "Muscle inconnu")
    }

    func testPrefixesUsedByLogic() {
        XCTAssertTrue(tr("CONTRACTE ! (\(1)/\(3))").hasPrefix(trd("CONTRACTE")))
        Lang.override = .fr
        XCTAssertEqual(tr("\(2) mois"), "2 mois")
    }
